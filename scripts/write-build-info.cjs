/* ============================================================================
   write-build-info.cjs
   ----------------------------------------------------------------------------
   BUILD_ID: AUTO-BUILD-INFO-01
   FILE: scripts/write-build-info.cjs

   Purpose
   - Generate build metadata before each production build
   - Write a small TypeScript module consumed by the About page

   Output
   - src/build/buildInfo.ts
   ============================================================================ */

const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const repoRoot = process.cwd();
const packageJsonPath = path.join(repoRoot, "package.json");
const outputDir = path.join(repoRoot, "src", "build");
const outputFile = path.join(outputDir, "buildInfo.ts");

function safeGit(args, fallback = "unknown") {
  try {
    return execFileSync("git", args, {
      cwd: repoRoot,
      stdio: ["ignore", "pipe", "ignore"],
    })
      .toString()
      .trim();
  } catch {
    return fallback;
  }
}

function escapeForTypeScript(value) {
  return JSON.stringify(String(value));
}

function renderBuildInfo({ version, commit, branch, builtAt, dirty }) {
  const displayCommit = dirty ? `${commit} + local changes` : commit;
  return `/* ============================================================================
   buildInfo.ts
   ----------------------------------------------------------------------------
   AUTO-GENERATED FILE — DO NOT EDIT BY HAND
   Generated by: scripts/write-build-info.cjs
   ============================================================================ */

export const buildInfo = {
  version: ${escapeForTypeScript(`v${version}`)},
  commit: ${escapeForTypeScript(commit)},
  displayCommit: ${escapeForTypeScript(displayCommit)},
  branch: ${escapeForTypeScript(branch)},
  builtAt: ${escapeForTypeScript(builtAt)},
  dirty: ${Boolean(dirty)},
} as const;
`;
}

function getPackageVersion() {
  const raw = fs.readFileSync(packageJsonPath, "utf8");
  const pkg = JSON.parse(raw);
  return pkg.version || "0.0.0";
}

function writeBuildInfo() {
  const version = getPackageVersion();
  const commit = safeGit(["rev-parse", "--short", "HEAD"]);
  const branch = safeGit(["rev-parse", "--abbrev-ref", "HEAD"]);
  const status = safeGit([
    "status",
    "--porcelain",
    "--untracked-files=normal",
    "--",
    ".",
    ":(exclude)src/build/buildInfo.ts",
  ], "");
  const dirty = status.length > 0;
  const fileContents = renderBuildInfo({
    version,
    commit,
    branch,
    builtAt: new Date().toISOString(),
    dirty,
  });

  fs.mkdirSync(outputDir, { recursive: true });
  fs.writeFileSync(outputFile, fileContents, "utf8");
  console.log(`Wrote build info to ${path.relative(repoRoot, outputFile)} (${commit}${dirty ? " + local changes" : ""})`);
}

if (require.main === module) {
  writeBuildInfo();
}

module.exports = { renderBuildInfo, writeBuildInfo };
